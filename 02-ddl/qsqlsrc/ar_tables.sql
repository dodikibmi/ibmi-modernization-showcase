-- =====================================================================
-- Stage 2 - DDS physical files -> SQL tables                (Db2 for i)
--
-- Step 1 of 3: the new tables. They get long SQL names and long column
-- names, but keep the old 10-character system names (FOR SYSTEM NAME /
-- FOR COLUMN) so that native programs and CL commands still find them.
--
-- New compared to DDS:
--   * primary keys and CHECK constraints: bad status codes and negative
--     amounts are refused by the database, whatever program writes;
--   * audit columns maintained by Db2 itself (who / when / which job),
--     IMPLICITLY HIDDEN so SELECT * and existing programs do not see them.
-- Every old column is NOT NULL WITH DEFAULT, like a DDS field: a
-- null-capable column would change the record format level identifier.
-- Library DODIKIBMI2 = data library on PUB400.
-- =====================================================================

CREATE TABLE DODIKIBMI2.AR_CUSTOMER FOR SYSTEM NAME ARCUST (
  CUSTOMER_ID     FOR COLUMN CUCUST  NUMERIC(6, 0)  NOT NULL WITH DEFAULT,
  CUSTOMER_NAME   FOR COLUMN CUNAME  CHAR(30)       NOT NULL WITH DEFAULT,
  CREDIT_LIMIT    FOR COLUMN CUCRLM  DECIMAL(9, 2)  NOT NULL WITH DEFAULT,
  BALANCE         FOR COLUMN CUBAL   DECIMAL(11, 2) NOT NULL WITH DEFAULT,
  CUSTOMER_STATUS FOR COLUMN CUSTAT  CHAR(1)        NOT NULL WITH DEFAULT 'A',
  CHANGED_AT      FOR COLUMN CUCHGTS TIMESTAMP NOT NULL
                  GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
                  IMPLICITLY HIDDEN,
  CHANGED_BY      FOR COLUMN CUCHGUS VARCHAR(18) GENERATED ALWAYS AS (USER) IMPLICITLY HIDDEN,
  CHANGED_JOB     FOR COLUMN CUCHGJB VARCHAR(28) GENERATED ALWAYS AS (QSYS2.JOB_NAME) IMPLICITLY HIDDEN,
  CONSTRAINT AR_CUSTOMER_PK PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT AR_CUSTOMER_STATUS_CK CHECK (CUSTOMER_STATUS IN ('A', 'H')),
  CONSTRAINT AR_CUSTOMER_LIMIT_CK CHECK (CREDIT_LIMIT >= 0)
) RCDFMT ARCUSTT;

CREATE TABLE DODIKIBMI2.AR_INVOICES FOR SYSTEM NAME ARINV (
  CUSTOMER_ID     FOR COLUMN INCUST  NUMERIC(6, 0)  NOT NULL WITH DEFAULT,
  INVOICE_NO      FOR COLUMN ININV   NUMERIC(7, 0)  NOT NULL WITH DEFAULT,
  INVOICE_DATE    FOR COLUMN INIDAT  NUMERIC(8, 0)  NOT NULL WITH DEFAULT,
  DUE_DATE        FOR COLUMN INDUE   NUMERIC(8, 0)  NOT NULL WITH DEFAULT,
  AMOUNT          FOR COLUMN INAMT   DECIMAL(9, 2)  NOT NULL WITH DEFAULT,
  PAID            FOR COLUMN INPAID  DECIMAL(9, 2)  NOT NULL WITH DEFAULT,
  LAST_PAY_DATE   FOR COLUMN INLPDT  NUMERIC(8, 0)  NOT NULL WITH DEFAULT,
  INVOICE_STATUS  FOR COLUMN INSTS   CHAR(1)        NOT NULL WITH DEFAULT 'O',
  CHANGED_AT      FOR COLUMN INCHGTS TIMESTAMP NOT NULL
                  GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
                  IMPLICITLY HIDDEN,
  CHANGED_BY      FOR COLUMN INCHGUS VARCHAR(18) GENERATED ALWAYS AS (USER) IMPLICITLY HIDDEN,
  CHANGED_JOB     FOR COLUMN INCHGJB VARCHAR(28) GENERATED ALWAYS AS (QSYS2.JOB_NAME) IMPLICITLY HIDDEN,
  CONSTRAINT AR_INVOICE_PK PRIMARY KEY (INVOICE_NO),
  CONSTRAINT AR_INVOICE_STATUS_CK CHECK (INVOICE_STATUS IN ('O', 'P')),
  CONSTRAINT AR_INVOICE_AMOUNT_CK CHECK (AMOUNT >= 0 AND PAID >= 0 AND PAID <= AMOUNT)
) RCDFMT ARINVT;

CREATE TABLE DODIKIBMI2.AR_PAYMENTS FOR SYSTEM NAME ARPAY (
  BATCH_NO        FOR COLUMN PYBAT   NUMERIC(5, 0)  NOT NULL WITH DEFAULT,
  SEQUENCE_NO     FOR COLUMN PYSEQ   NUMERIC(5, 0)  NOT NULL WITH DEFAULT,
  CUSTOMER_ID     FOR COLUMN PYCUST  NUMERIC(6, 0)  NOT NULL WITH DEFAULT,
  PAY_DATE        FOR COLUMN PYDATE  NUMERIC(8, 0)  NOT NULL WITH DEFAULT,
  AMOUNT          FOR COLUMN PYAMT   DECIMAL(9, 2)  NOT NULL WITH DEFAULT,
  PAY_STATUS      FOR COLUMN PYSTS   CHAR(1)        NOT NULL WITH DEFAULT,
  MESSAGE         FOR COLUMN PYMSG   CHAR(30)       NOT NULL WITH DEFAULT,
  CHANGED_AT      FOR COLUMN PYCHGTS TIMESTAMP NOT NULL
                  GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
                  IMPLICITLY HIDDEN,
  CHANGED_BY      FOR COLUMN PYCHGUS VARCHAR(18) GENERATED ALWAYS AS (USER) IMPLICITLY HIDDEN,
  CHANGED_JOB     FOR COLUMN PYCHGJB VARCHAR(28) GENERATED ALWAYS AS (QSYS2.JOB_NAME) IMPLICITLY HIDDEN,
  CONSTRAINT AR_PAYMENT_PK PRIMARY KEY (BATCH_NO, SEQUENCE_NO),
  CONSTRAINT AR_PAYMENT_STATUS_CK CHECK (PAY_STATUS IN (' ', 'P', 'E'))
) RCDFMT ARPAYT;

LABEL ON TABLE DODIKIBMI2.AR_CUSTOMER IS 'Customer master';
LABEL ON TABLE DODIKIBMI2.AR_INVOICES  IS 'Invoices';
LABEL ON TABLE DODIKIBMI2.AR_PAYMENTS  IS 'Payments received';
